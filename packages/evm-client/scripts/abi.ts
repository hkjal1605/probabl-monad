/** Regenerates src/abi.ts from the Foundry build (run `forge build` in contracts/ first).
 * The exchange and each Δ-vault serve two runtimes at one address: their own functions and,
 * through the fallback, their module's. One merged ABI describes each address. */
import { resolve } from "node:path";

type Item = { type: string; name?: string; inputs?: { type: string }[] };
const signature = (item: Item) =>
  `${item.type}:${item.name ?? ""}(${(item.inputs ?? []).map((input) => input.type).join(",")})`;
const read = async (name: string) =>
  (
    (await Bun.file(
      resolve(import.meta.dir, `../../../contracts/out/${name}.sol/${name}.json`),
    ).json()) as { abi: Item[] }
  ).abi;
async function merge(names: string[]) {
  const merged = new Map<string, Item>();
  for (const name of names)
    for (const item of await read(name))
      if (item.type !== "constructor" && item.type !== "fallback")
        merged.set(signature(item), item);
  return [...merged.values()].sort((a, b) => signature(a).localeCompare(signature(b)));
}

const exchange = await merge(["ConditionalStocks", "ConditionalStocksAdmin"]);
const vault = await merge(["DeltaVault", "DeltaVaultAdmin"]);
await Bun.write(
  resolve(import.meta.dir, "../src/abi.ts"),
  `// Generated by scripts/abi.ts from contracts/out. Do not edit.
export const conditionalStocksAbi = ${JSON.stringify(exchange, null, 2)} as const;

export const deltaVaultAbi = ${JSON.stringify(vault, null, 2)} as const;
`,
);
console.info(`abi.ts: ${exchange.length} exchange and ${vault.length} vault entries`);
