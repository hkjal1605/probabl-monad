/** Regenerates src/abi.ts from the Foundry build (run `forge build` in contracts/ first).
 * The exchange address serves both runtimes: its own functions and, through the fallback,
 * the admin module's. One merged ABI describes that single address. */
import { resolve } from "node:path";

type Item = { type: string; name?: string; inputs?: { type: string }[] };
const signature = (item: Item) =>
  `${item.type}:${item.name ?? ""}(${(item.inputs ?? []).map((input) => input.type).join(",")})`;
const read = async (name: string) =>
  (
    (await Bun.file(
      resolve(import.meta.dir, `../../../contracts/out/${name}.sol/${name}.json`),
    ).json()) as { abi: Item[] }
  ).abi;

const merged = new Map<string, Item>();
for (const name of ["ConditionalStocks", "ConditionalStocksAdmin"])
  for (const item of await read(name))
    if (item.type !== "constructor" && item.type !== "fallback") merged.set(signature(item), item);
const abi = [...merged.values()].sort((a, b) => signature(a).localeCompare(signature(b)));
await Bun.write(
  resolve(import.meta.dir, "../src/abi.ts"),
  `// Generated by scripts/abi.ts from contracts/out. Do not edit.\nexport const conditionalStocksAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.info(`abi.ts: ${abi.length} entries`);
